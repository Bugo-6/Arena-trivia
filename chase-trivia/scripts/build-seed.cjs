// Builds supabase/seed.sql from src/data/questions/*.json
// To add questions: append objects to a JSON file (correct answer FIRST), then run `npm run seed:build`
// and run the generated supabase/seed.sql again (it is idempotent: duplicates are skipped).
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "src", "data", "questions");
const cats = ["general", "science", "geography", "history", "sports", "entertainment", "technology", "music", "israel", "food"];
const diffs = ["easy", "medium", "hard"];
const all = [];
const seen = new Set();

for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".json")).sort()) {
  const arr = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  arr.forEach((x, i) => {
    const where = `${f}#${i}`;
    if (typeof x.q !== "string" || !x.q.trim()) throw new Error(`${where}: missing question`);
    if (!cats.includes(x.cat)) throw new Error(`${where}: bad category ${x.cat}`);
    if (!diffs.includes(x.diff)) throw new Error(`${where}: bad difficulty ${x.diff}`);
    if (!Array.isArray(x.a) || x.a.length !== 4 || new Set(x.a).size !== 4 || x.a.some((s) => typeof s !== "string" || !s.trim()))
      throw new Error(`${where}: needs 4 distinct answers`);
    if (seen.has(x.q)) throw new Error(`${where}: duplicate question`);
    seen.add(x.q);
    all.push({ cat: x.cat, diff: x.diff, q: x.q, a: x.a });
  });
}

const json = JSON.stringify(all);
if (json.includes("$json$")) throw new Error("question text contains reserved delimiter");
const sql = `-- GENERATED by scripts/build-seed.cjs — do not edit by hand (${all.length} questions)
insert into public.questions (cat, diff, q, answers)
select x->>'cat', x->>'diff', x->>'q', x->'a'
from jsonb_array_elements($json$${json}$json$::jsonb) as x
on conflict (q) do nothing;
`;
fs.writeFileSync(path.join(__dirname, "..", "supabase", "seed.sql"), sql);
console.log(`seed.sql written with ${all.length} questions`);
